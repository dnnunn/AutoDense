import subprocess
import os
sys.path.append('.')

def load_run_report(output_dir: str):
    """Load run report from output directory."""
    report_path = os.path.join(output_dir, 'run_report.json')
    try:
        with open(report_path, 'r') as f:
            return json.load(f)
    except FileNotFoundError:
        return None

def run_analysis_with_config(config_name: str, output_suffix: str):
    """Run analysis with specified config using build script approach."""
    
    # Create custom build script calls for optimized configs
    if 'etbr' in config_name:
        cmd = [
            'java', '-cp', 'autodense/plugin/target/classes:autodense/plugin/target/dependency/*',
            'com.betterdairy.autodense.cli.AutotuneAnalysisCLI', '--no-exit',
            'etbr_agarose', 'samples/etbr_gel.jpg', config_name, f'output/test_etbr{output_suffix}'
        ]
    elif 'sds' in config_name:
        cmd = [
            'java', '-cp', 'autodense/plugin/target/classes:autodense/plugin/target/dependency/*',
            'com.betterdairy.autodense.cli.AutotuneAnalysisCLI', '--no-exit', 
            'sds_page', 'samples/sds_gel.jpg', config_name, f'output/test_sds{output_suffix}'
        ]
    else:
        return None
    
    try:
        print(f"Running: {' '.join(cmd[-4:])}")
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        
        if result.returncode == 0:
            return load_run_report(f'output/test_{config_name.split("/")[1].split("_")[0]}{output_suffix}')
        else:
            print(f"Error: {result.stderr}")
            return None
            
    except subprocess.TimeoutExpired:
        print("Analysis timed out")
        return None
    except Exception as e:
        print(f"Error running analysis: {e}")
        return None

